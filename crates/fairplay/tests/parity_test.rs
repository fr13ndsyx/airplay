//! Parity tests — FairPlay 实现的正确性验证。
//!
//! 测试向量来源：
//! - SapHash 测试用例：6 个 sap_hash 测试
//! - OmgHax 测试用例：generate_session_key、decrypt_message (x2)、
//!   generate_key_schedule (x2)、cycle
//!
//! `i8` 字面量在 -128..127 范围，`u8` 在 0..255 范围。
//! 测试向量使用 `i8` 字面量，通过 `.map(|b| b as u8)` 进行位模式保持转换。

use fairplay::consts::{DEFAULT_SAP, INITIAL_SESSION_KEY};
use fairplay::{omg_hax, sap_hash};

/// 将有符号字节数组转换为无符号。
fn jbytes<const N: usize>(arr: [i8; N]) -> [u8; N] {
    arr.map(|b| b as u8)
}

/// 将 i32 二维数组转换为 u32 二维数组。
fn jkeys(arr: [[i32; 4]; 11]) -> [[u32; 4]; 11] {
    arr.map(|row| row.map(|v| v as u32))
}

